  static Future<void> loadDataset() async {
    try {
      final jsonString = await rootBundle.loadString('assets/word_wheel_300_levels.json');
      _parseDataset(jsonString);
    } catch (_) {
      _tryLoadFromFile();
    }

    try {
      final dailyJson = await rootBundle.loadString('assets/daily_challenge_100_levels.json');
      _parseDailyDataset(dailyJson);
    } catch (_) {
      _tryLoadDailyFromFile();
    }

    _datasetLoaded = true;
  }

  static void _tryLoadFromFile() {
    try {
      final file = File('assets/word_wheel_300_levels.json');
      if (file.existsSync()) {
        final jsonString = file.readAsStringSync();
        _parseDataset(jsonString);
      }
    } catch (_) {}
  }

  static void _tryLoadDailyFromFile() {
    try {
      final file = File('assets/daily_challenge_100_levels.json');
      if (file.existsSync()) {
        final jsonString = file.readAsStringSync();
        _parseDailyDataset(jsonString);
      }
    } catch (_) {}
  }

  static void _parseDailyDataset(String jsonString) {
    try {
      final Map<String, dynamic> root = jsonDecode(jsonString);
      final List<dynamic> list = root['levels'];
      _daily100Levels = list.map((item) {
        final map = item as Map<String, dynamic>;
        final int levelNum = map['level'] as int;
        final List<dynamic> lettersList = map['letters'] as List<dynamic>;
        final String letters = lettersList.map((e) => e.toString().toUpperCase()).join('');
        final List<String> required = ((map['words_to_make'] ?? map['required_words']) as List<dynamic>)
            .map((e) => e.toString().toUpperCase())
            .toList();

        return Level(
          id: -levelNum,
          theme: "Daily Challenge",
          letters: letters,
          requiredWords: required,
          bonusWords: [],
          hardWord: null,
          difficulty: map['difficulty'] == 'Easy' ? 1 : (map['difficulty'] == 'Medium' ? 2 : 3),
          reward: 100,
          layoutPattern: ((levelNum - 1) % 8) + 1,
        );
      }).toList();
    } catch (_) {}
  }

  static void _parseDataset(String jsonString) {
    final Map<String, dynamic> root = jsonDecode(jsonString);
    final List<dynamic> list = root['levels'];
    _main300Levels = list.map((item) {
      final map = item as Map<String, dynamic>;
      final int levelNum = map['level'] as int;
      final List<dynamic> lettersList = map['letters'] as List<dynamic>;
      final String letters = lettersList.map((e) => e.toString().toUpperCase()).join('');
      final List<String> required = ((map['words_to_make'] ?? map['required_words']) as List<dynamic>)
          .map((e) => e.toString().toUpperCase())
          .toList();
      final List<String> bonus = (map['bonus_words'] as List<dynamic>?)
              ?.map((e) => e.toString().toUpperCase())
              .toList() ??
          [];
      final String? hard = map['hard_word']?.toString().toUpperCase();

      return Level(
        id: levelNum,
        theme: "World ${(levelNum - 1) ~/ 20 + 1}",
        letters: letters,
        requiredWords: required,
        bonusWords: bonus,
        hardWord: hard,
        difficulty: map['difficulty'] == 'Easy' ? 1 : (map['difficulty'] == 'Medium' ? 2 : 3),
        reward: 25 + (levelNum % 10),
        layoutPattern: ((levelNum - 1) % 8) + 1,
      );
    }).toList();
    _datasetLoaded = _main300Levels.isNotEmpty;
  }
