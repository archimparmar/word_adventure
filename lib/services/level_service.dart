  static int getRequiredWordCountForLevel(int levelId) {
    int absLevel = levelId.abs();
    if (absLevel <= 1) return 3;
    if (absLevel <= 4) return 4;
    if (absLevel <= 15) return 5;
    if (absLevel <= 30) return 6;
    if (absLevel <= 50) return 7;
    if (absLevel <= 80) return 8;
    if (absLevel <= 120) return 9;
    if (absLevel <= 170) return 10;
    if (absLevel <= 220) return 11;
    return 12;
  }

  static Level _buildLevelForProgression(int id, Level baseLevel) {
    int targetCount = getRequiredWordCountForLevel(id);
    String mainWord = baseLevel.letters.toUpperCase();

    Set<String> pool = {};
    for (String w in baseLevel.requiredWords) {
      if (w.length >= 3) pool.add(w.toUpperCase());
    }
    for (String w in baseLevel.bonusWords) {
      if (w.length >= 3) pool.add(w.toUpperCase());
    }
    if (baseLevel.hardWord != null && baseLevel.hardWord!.length >= 3) {
      pool.add(baseLevel.hardWord!.toUpperCase());
    }
    pool.add(mainWord);

    Map<String, int> letterCounts = {};
    for (int i = 0; i < mainWord.length; i++) {
      String char = mainWord[i];
      letterCounts[char] = (letterCounts[char] ?? 0) + 1;
    }

    bool canForm(String word) {
      Map<String, int> counts = {};
      for (int i = 0; i < word.length; i++) {
        String char = word[i];
        counts[char] = (counts[char] ?? 0) + 1;
        if ((counts[char] ?? 0) > (letterCounts[char] ?? 0)) return false;
      }
      return true;
    }

    List<String> validPool = pool.where(canForm).toList();
    List<String> candidates = validPool.where((w) => w != mainWord).toList();

    candidates.sort((a, b) {
      int cmp = a.length.compareTo(b.length);
      if (cmp != 0) return cmp;
      return a.compareTo(b);
    });

    List<String> selectedRequired = [];
    int candidatesToTake = math.min(targetCount - 1, candidates.length);

    for (int i = 0; i < candidatesToTake; i++) {
      selectedRequired.add(candidates[i]);
    }
    selectedRequired.add(mainWord);

    selectedRequired.sort((a, b) {
      int cmp = a.length.compareTo(b.length);
      if (cmp != 0) return cmp;
      return a.compareTo(b);
    });

    List<String> remainingBonus = validPool.where((w) => !selectedRequired.contains(w)).toList();

    return Level(
      id: id,
      theme: id < 0 ? "Daily Challenge" : baseLevel.theme,
      letters: baseLevel.letters,
      requiredWords: selectedRequired,
      bonusWords: remainingBonus,
      hardWord: baseLevel.hardWord,
      difficulty: baseLevel.difficulty,
      reward: id < 0 ? 100 : baseLevel.reward,
      layoutPattern: baseLevel.layoutPattern,
    );
  }

  static Level getLevel(int id) {
    if (!_datasetLoaded || _main300Levels.isEmpty) {
      _tryLoadFromFile();
    }

    if (id < 0) {
      return getDailyLevel(DateTime.now());
    }

    if (_main300Levels.isNotEmpty) {
      int clampedId = id.clamp(1, 300);
      return _main300Levels[clampedId - 1];
    }

    int clampedId = id.clamp(1, levels.length);
    return _buildLevelForProgression(clampedId, levels[clampedId - 1]);
  }

  static int getDailyDayNumber(DateTime date) {
    final d = DateTime(date.year, date.month, date.day);
    final start = DateTime(_startDate.year, _startDate.month, _startDate.day);
    int diffDays = d.difference(start).inDays;
    return ((diffDays % 100) + 100) % 100 + 1;
  }

  static bool isDailyDatasetCompleted(DateTime date) {
    return false;
  }

  static Level getDailyLevel(DateTime date) {
    if (!_datasetLoaded || _daily100Levels.isEmpty) {
      _tryLoadDailyFromFile();
    }

    int dayNum = getDailyDayNumber(date);
    int index = dayNum - 1;

    if (_daily100Levels.isNotEmpty && index < _daily100Levels.length) {
      Level l = _daily100Levels[index];
      return Level(
        id: -dayNum,
        theme: "Daily Challenge",
        letters: l.letters,
        requiredWords: l.requiredWords,
        bonusWords: l.bonusWords,
        hardWord: l.hardWord,
        difficulty: l.difficulty,
        reward: 100,
        layoutPattern: l.layoutPattern,
      );
    }

    // Fallback if dataset not yet loaded
    return Level(
      id: -dayNum,
      theme: "Daily Challenge",
      letters: "PLANET",
      requiredWords: ["PLANET", "PLANE", "PLANT"],
      bonusWords: [],
      hardWord: null,
      difficulty: 1,
      reward: 100,
      layoutPattern: 1,
    );
  }
